# 基本能力的题目。
#
# 一道题有四样东西：
#   名字       这道题叫什么
#   初始文件   开始前放进临时 Agent 文件夹里的文件。不写的文件用 templates/ 里的空白模板
#   用户说     用户依次说的话，一句是一轮对话
#   检查       跑完以后逐条检查，全部通过这一次才算对
#
# 可以再加一项"审批"：需要审批时自动回答什么，不写就是同意（True）。
# 还可以加一项"身份"：写"专属"表示它不是主 bot，不能改公共的 user/。不写就是主 bot。
# 专属 Agent 还可以加一项"能力包"：给它打开哪些能力包，比如 ["notify"]。不写就只有基本能力。

