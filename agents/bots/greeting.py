# 新 Agent 先开口：第一次和它对话时，由它先打招呼、介绍自己，不让用户进去以后没人说话。
#
# 做法：代码替用户发一条"开场指令"（OPENING）当作第一句话，它的回答就是招呼。
# 命令行、飞书、以后的网页，用的都是这一条，所以从哪里建，它说的都是同一种开场白。

OPENING = """（这条是系统替用户发的，用户看不到）
你刚刚被用户新建出来，这是你们的第一次对话。现在由你先开口，向用户打个招呼并介绍自己：

- 你的名字和角色写在 AGENT.md 里。
- 角色是某个具体领域的（比如英语老师、编程工程师）：以这个角色介绍自己，说说在这个领域你能帮上什么。
- 角色是通用助手的：简单介绍自己，说说你现在能做什么，再问用户主要想让你做什么。
- 说到"能做什么"，只能说能力清单里"已启用"的，加上聊天、解释、写文字、出主意这些不需要工具的事。和你的角色相关、但"没有启用"或"还没接入"的能力，要如实说现在还做不了。
- 不要调用任何工具。纯文字，不超过 120 个字，不要用表格和标题。"""

OPENING_NOTE = "（刚新建，它先开口）"      # 每日记录里代替上面那一大段


def is_fresh(ctx):
    """这个 Agent 是不是一句话都还没说过：它的文件夹里还没有每日记录（memory/）。

    主 bot 不算：它有自己的首次引导（BOOTSTRAP.md）。
    """
    return ctx.bot_id != "main" and not (ctx.folder / "memory").exists()
